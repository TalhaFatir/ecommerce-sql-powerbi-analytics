/* Problem 11: Top 5 sellers by revenue and order status performance. */
select top 5
    s.seller_id,
    s.seller_name,
    count(distinct o.order_id) as total_orders,
    count(distinct case when order_status = 'Completed' then o.order_id end) as completed_orders,
    count(distinct case when order_status = 'Inprogress' then o.order_id end) as inprogress_orders,
    count(distinct case when order_status = 'Returned' then o.order_id end) as returned_orders,
    count(distinct case when order_status = 'Cancelled' then o.order_id end) as cancelled_orders,
    cast(
        count(distinct case when order_status = 'Completed' then o.order_id end) * 100.0
        / count(distinct o.order_id)
        as decimal(5,2)
    ) as percentage_of_completed_orders,
    sum(oi.quantity * oi.price_per_unit) as total_revenue
from sellers as s
join orders as o
on s.seller_id = o.seller_id
join order_items as oi
on o.order_id = oi.order_id
group by 
    s.seller_id,
    s.seller_name
order by total_revenue desc;

/* Problem 12: Product unit profit ranking. */
select
    product_id,
    product_name,
    price,
    cogs,
    (price - cogs) as profit,
    rank() over(order by (price - cogs) desc) as ranking
from products
order by ranking asc;

/* Problem 13: Top 10 most returned products and return rate. */
select top 10
    p.product_id,
    p.product_name,
    sum(case when o.order_status = 'Returned' then oi.quantity else 0 end) as returned_products,
    cast(
        sum(case when o.order_status = 'Returned' then oi.quantity else 0 end) * 100.0
        / nullif(sum(oi.quantity),0)
        as decimal(5,2)
    ) as returned_percentage,
    sum(oi.quantity) as total_units_sold
from products as p
join order_items as oi
on oi.product_id = p.product_id
join orders as o
on o.order_id = oi.order_id
group by 
    p.product_id,
    p.product_name
order by returned_products desc;

