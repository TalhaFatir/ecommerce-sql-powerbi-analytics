/* Problem 6: For each customer, add up the value of every order they have ever placed to calculate their total lifetime spending. 
Then compare all customers and assign a rank so the highest-spending customer appears first. */
with customer_lifetime_spending as
(
select
    c.Customer_ID,
    c.first_name,
    c.last_name,
    coalesce(sum(oi.quantity * oi.price_per_unit), 0) as lifetime_spending
from customers as c
left join orders as o
on c.Customer_ID = o.Customer_Id
left join order_items as oi
on o.order_id = oi.order_id
group by 
    c.Customer_ID,
    c.first_name,
    c.last_name
)
select
    Customer_ID,
    first_name,
    last_name,
    lifetime_spending,
    rank() over(order by lifetime_spending desc) as ranking
from customer_lifetime_spending 
order by ranking;

/* Problem 7: For each customer state, calculate the total sales generated by every product category. 
Then, within each state, find the category with the smallest total sales amount and display the state, 
category name, and that category’s total sales. */
with category_sales_amount_per_state as 
(
select
    c.state,
    cat.category_id,
    cat.category_name,
    sum(oi.quantity * oi.price_per_unit) as total_sales
from customers as c
join orders as o
on c.Customer_Id = o.customer_ID
join order_items as oi
on o.order_id = oi.order_id
join products as p 
on p.product_id = oi.product_id
join category as cat 
on cat.category_id = p.category_id
group by 
    c.state,
    cat.category_id,
    cat.category_name
),
ranked_categories as 
(
select 
    state,
    category_id,
    category_name,
    total_sales,
    rank() over(partition by state order by total_sales asc) as sales_rank
from category_sales_amount_per_state
)
select
    state,
    category_name,
    total_sales
from ranked_categories 
where sales_rank = 1
order by state;

/* Problem 8: Find all products whose current stock is below 10 units. */
select
    p.product_id,
    p.product_name,
    i.stock,
    i.last_stock_date,
    i.warehouse_id
from products as p
join inventory as i
on p.product_id = i.product_id
where i.stock < 10
order by i.stock asc;

/* Problem 9: Find all orders where the shipping date happened more than 3 days after the order date. */
select
    c.Customer_ID,
    c.first_name,
    c.last_name,
    s.shipping_providers,
    o.order_id,
    o.order_date,
    s.shipping_date,
    datediff(day, o.order_date, s.shipping_date) as shipping_duration,
    o.order_status
from customers as c
join orders as o
on c.Customer_ID = o.customer_id
join shipping as s 
on o.order_id = s.order_id
where s.shipping_date > dateadd(day,3,o.order_date)
order by shipping_duration desc;

/* Problem 10: Payment status distribution and percentage share. */
with payment_info as 
