/* Problem 19: Shipping provider revenue, order count, and average shipping days. */
with order_summary as 
(
select
    o.order_id,
    o.order_date,
    s.shipping_date,
    s.shipping_providers,
    sum(oi.quantity * oi.price_per_unit) as order_revenue
from orders as o
left join order_items as oi
on o.order_id = oi.order_id
left join shipping as s
on s.order_id = oi.order_id
group by
    o.order_id,
    o.order_date,
    s.shipping_date,
    s.shipping_providers
)
select
    shipping_providers,
    sum(order_revenue) as total_revenue,
    count(order_id) as total_orders,
    cast(
        avg(
            cast(datediff(day, order_date, shipping_date) as decimal(10,2))
        ) as decimal(10,2)
    ) as average_shipping_days
from order_summary
group by shipping_providers;

/* Problem 20: Top 10 products with biggest revenue decline, 2022 vs 2023. */
with product_revenue as 
( 
select 
    cat.category_name,
    p.product_id,
    p.product_name,
    sum(case when year(o.order_date) = 2022 then oi.quantity * oi.price_per_unit else 0 end) as revenue_2022,
    sum(case when year(o.order_date) = 2023 then oi.quantity * oi.price_per_unit else 0 end) as revenue_2023
from products as p 
left join category as cat 
on p.category_id = cat.category_id
left join order_items as oi 
on p.product_id = oi.product_id
left join orders as o
on o.order_id = oi.order_id
group by 
    cat.category_name,
    p.product_id,
    p.product_name
)
select top 10
    category_name,
    product_id,
    product_name,
    revenue_2022,
    revenue_2023,
    round(
        (revenue_2023 - revenue_2022) * 100.0
        / nullif(revenue_2022,0),2
    ) as decrease_ratio
from product_revenue
where revenue_2022 > 0 
and revenue_2023 < revenue_2022
order by decrease_ratio;

/* Problem 21: Automatically reduce inventory when new order-item records are inserted. */
create trigger trg_reduce_inventory
on order_items
after insert 
as
begin

    update i
    set i.stock = i.stock - x.quantity_sold

    from inventory as i

    join
    (
        select
            product_id,
            sum(quantity) as quantity_sold
        from inserted
        group by product_id
    ) as x

    on i.product_id = x.product_id;

end;
