/* Problem 1: Top Selling Products
Query the top 10 products by total sales value.
Challenge: Include product name, total quantity sold,
and total sales value. */
select top 10
p.product_name,
sum(oi.quantity) AS total_quantity_sold,
sum(oi.quantity * oi.price_per_unit) AS total_sales_value
from order_items as oi
left join products as p 
on oi.product_id = p.product_id
group by p.product_id, p.product_name
order by total_sales_value desc;

/* Problem 2: Show the revenue for each category and show how much each category contributes to the total revenue as a percentage.*/
with category_revenue as
(
select
    c.category_id,
    c.category_name,
    sum(oi.quantity * oi.price_per_unit) as total_revenue
from order_items as oi
left join products as p
on oi.product_id = p.product_id
left join category as c
on p.category_id = c.category_id 
group by c.category_id, c.category_name 
)
select
    category_id,
    category_name,
    round(
        (total_revenue * 100.0)/sum(total_revenue) over(),2
        ) as revenue_percentage,
        total_revenue
from category_revenue
order by total_revenue desc;

/* Problem 3. For every customer, find the average amount of money they spend per order. 
Only show customers who have placed more than 5 orders. */
with order_total as 
(
select 
    o.order_id,
    o.customer_id,
    sum(oi.quantity * oi.price_per_unit) as order_value
from orders as o
left join order_items as oi
on o.order_id = oi.order_id
group by 
o.order_id,
o.customer_id
)
select
    c.customer_id,
    c.first_name,
    c.last_name,
    count(*) as number_of_orders,
    round(avg(ot.order_value),2) as avg_order_value
from order_total as ot
left join customers as c
on c.customer_id = ot.customer_id
group by 
    c.customer_id,
    c.first_name,
    c.last_name
having count(*) > 5
order by avg_order_value desc;

/* Problem 4: For each month in the most recent 12 months, calculate the total sales made during that month.
Also show the previous month’s sales beside it so you can compare month-to-month performance.*/
with current_month_sales as
(
select
    datefromparts(
                    year(o.order_date),
                    month(o.order_date),
                    1
                    ) as sales_month,
    sum(oi.quantity * oi.price_per_unit) as sales_amount_per_month
    from orders as o
    left join order_items as oi
    on o.order_id = oi.order_id
    where o.order_date >= 
    (
        select 
            dateadd(
                    month,
                    -11,
                    datefromparts(
                    year(max(o2.order_date)),
                    month(max(o2.order_date)),
                    1)
                    )
        from orders as o2
    )
    group by datefromparts(
                    year(o.order_date),
                    month(o.order_date),
                    1
                    )
)
select
        sales_month,
        sales_amount_per_month,
        lag(sales_amount_per_month) over
        (order by sales_month) as previous_month_sales
from current_month_sales
order by sales_month;


