/* Problem 15: Inactive sellers relative to latest dataset order date. */
select 
    s.seller_id,
    s.seller_name,
    max(o.order_date) as last_order_date,
    coalesce(sum(oi.quantity * oi.price_per_unit),0) as total_sales
from sellers as s
